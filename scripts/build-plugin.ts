/**
 * Builds the installable skill: plugin/skills/skills-dashboard/{app/, scripts/server.mjs}.
 * The output is committed so people who install the plugin never need to build anything.
 *
 *   bun run build:plugin
 */
import { $ } from 'bun'
import fs from 'node:fs/promises'
import path from 'node:path'

const root = path.resolve(import.meta.dir, '..')
// The plugin lives in its own folder so installs copy only the skill — a package.json at the
// plugin root would make Claude Code install all our dev dependencies for every user.
const skillDir = path.join(root, 'plugin', 'skills', 'skills-dashboard')

await $`bun --bun tsc`.cwd(root)
await $`bun --bun vite build`.cwd(root)

const appDir = path.join(skillDir, 'app')
await fs.rm(appDir, { recursive: true, force: true })
await fs.cp(path.join(root, 'dist'), appDir, { recursive: true })

const result = await Bun.build({
  entrypoints: [path.join(root, 'server', 'standalone.ts')],
  target: 'node',
  format: 'esm',
  outdir: path.join(skillDir, 'scripts'),
  naming: 'server.mjs',
  banner: '// Generated by `bun run build:plugin` from server/ — edit the sources, not this file.',
})
if (!result.success) {
  for (const log of result.logs) console.error(log)
  process.exit(1)
}

const size = (await fs.stat(path.join(skillDir, 'scripts', 'server.mjs'))).size
console.log(`\n✓ Skill built in ${path.relative(root, skillDir)}  (server.mjs ${(size / 1024).toFixed(0)} KB)`)
